package org.c2.supportticketsystem.model.enums;

/**
 * Represents the priority level of a ticket.
 * 
 * <p>Valid priority values:
 * <ul>
 *   <li>LOW - Low priority issue</li>
 *   <li>MEDIUM - Medium priority issue</li>
 *   <li>HIGH - High priority issue</li>
 *   <li>URGENT - Urgent priority issue</li>
 * </ul>
 */
public enum Priority {
    /**
     * Low priority issue.
     */
    LOW,

    /**
     * Medium priority issue.
     */
    MEDIUM,

    /**
     * High priority issue.
     */
    HIGH,

    /**
     * Urgent priority issue.
     */
    URGENT
}
